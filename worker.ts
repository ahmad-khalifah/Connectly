// Front door of the Cloudflare Worker (wrangler.jsonc "main").
//
// Workers Free allows 10 ms of CPU per request. Rendering a Next.js page
// costs 20 to 260 ms (measured on staging, 21 Nov 2026), so the customer
// path never renders one:
//   * /portal, /connect and /success are static files, served by Cloudflare
//     from the assets folder before this code runs (scripts/cf-static-pages.mjs);
//   * the API those pages call, and the Korapay webhook, are answered here by
//     plain handlers (lib/http/customer-api.ts) without starting Next.js.
//   * the admin pages' data (/api/admin/me, /api/admin/view/*, /api/admin/sweep)
//     likewise (lib/http/admin-api.ts), each request checked for an admin;
//   * the admin's save and edit actions (lib/http/admin-routes.ts), which
//     check the caller themselves.
// Everything else goes to the Next.js worker built by OpenNext.
//
// The .open-next files exist only after `npm run cf:build`, so the type
// checker may or may not see them: @ts-ignore (not @ts-expect-error) suits both.

// eslint-disable-next-line @typescript-eslint/ban-ts-comment
// @ts-ignore: generated by opennextjs-cloudflare build
import { runWithCloudflareRequestContext } from './.open-next/cloudflare/init.js';
// eslint-disable-next-line @typescript-eslint/ban-ts-comment
// @ts-ignore: generated by opennextjs-cloudflare build
import nextWorker from './.open-next/worker.js';
import { customerApiRoute } from './lib/http/customer-api';
import { adminApiRoute } from './lib/http/admin-api';
import { adminActionRoute } from './lib/http/admin-routes';

// eslint-disable-next-line @typescript-eslint/ban-ts-comment
// @ts-ignore: generated by opennextjs-cloudflare build
export { DOQueueHandler, DOShardedTagCache, BucketCachePurge } from './.open-next/worker.js';

type Ctx = { waitUntil(p: Promise<unknown>): void; passThroughOnException(): void };

const frontDoor = {
  async fetch(request: Request, env: Record<string, unknown>, ctx: Ctx): Promise<Response> {
    const { pathname } = new URL(request.url);
    const handler =
      customerApiRoute(request.method, pathname) ?? adminApiRoute(request.method, pathname) ?? adminActionRoute(request.method, pathname);
    if (!handler) return nextWorker.fetch(request, env, ctx);
    // The same request context OpenNext sets up, so process.env holds the
    // Worker's variables and secrets for lib/env.ts and lib/db/client.ts.
    return runWithCloudflareRequestContext(request, env, ctx, async () => {
      try {
        return await handler(request);
      } catch (error) {
        console.error('[FRONT_DOOR]', request.method, new URL(request.url).pathname, error);
        // ok/error for the portal's checkout form, message for everything else.
        const message = 'Something went wrong. Please try again.';
        return new Response(JSON.stringify({ ok: false, error: message, message }), {
          status: 500,
          headers: { 'Content-Type': 'application/json; charset=utf-8', 'Cache-Control': 'no-store' },
        });
      }
    });
  },
};

export default frontDoor;
