// WireGuard peers for the hub. The controller runs unprivileged, so it cannot
// change the WireGuard interface itself. It writes the list of router peers
// (public key + its one tunnel address) to a file; a small root-owned script
// (deploy/wg-peers-sync.sh, triggered by a systemd path unit) validates every
// line again and applies it with `wg syncconf`. Routers that are retired, or
// have no key or address, are left out, which removes them from the hub.

import fs from 'node:fs';
import path from 'node:path';
import type { RouterRow } from './db.ts';

const WG_KEY = /^[A-Za-z0-9+/]{42}[AEIMQUYcgkosw048]=$/;
const IPV4 = /^10\.77\.([0-3])\.(\d{1,3})$/;

export function renderPeers(routers: (RouterRow & { wg_public_key?: string | null })[]): string {
  const lines = ['# Generated by the Connectly controller. Applied by wg-peers-sync.sh. Do not edit.'];
  for (const r of [...routers].sort((a, b) => a.identifier.localeCompare(b.identifier))) {
    if (r.connection_method !== 'wireguard' || r.lifecycle_status === 'retired') continue;
    if (!r.wg_public_key || !WG_KEY.test(r.wg_public_key) || !r.tunnel_ip || !IPV4.test(r.tunnel_ip)) continue;
    lines.push('', '[Peer]', `# ${r.identifier.replace(/[^A-Za-z0-9._-]/g, '_')}`, `PublicKey = ${r.wg_public_key}`, `AllowedIPs = ${r.tunnel_ip}/32`);
  }
  return lines.join('\n') + '\n';
}

/** Writes the file atomically, only when its content changes. Returns true if it changed. */
export function writePeersFile(file: string, content: string): boolean {
  try {
    if (fs.readFileSync(file, 'utf8') === content) return false;
  } catch {
    /* first write */
  }
  const tmp = path.join(path.dirname(file), `.${path.basename(file)}.${process.pid}.tmp`);
  fs.writeFileSync(tmp, content, { mode: 0o644 });
  fs.renameSync(tmp, file);
  return true;
}
